#!/usr/bin/env bash
#
# update_vps_asns.sh - Fetch and generate Anubis botPolicy YAML snippet from vps-ranges/vpsh.txt
#
# Source list: https://github.com/the-furry-hubofeverything/vps-ranges/blob/main/vpsh.txt
# Note: Cloudflare WARP ASNs (13335, 209242) are explicitly excluded.
#

set -euo pipefail

OUTPUT_FILE="${OUTPUT_FILE:-${1:-./vpsh_asns.yaml}}"
URL="https://raw.githubusercontent.com/the-furry-hubofeverything/vps-ranges/main/vpsh.txt"
TMP_FILE="${OUTPUT_FILE}.tmp.$$"

echo "[*] Fetching VPS ASN list from ${URL}..."

python3 - << EOF
import sys
import urllib.request
import os

url = "${URL}"
tmp_file = "${TMP_FILE}"
out_file = "${OUTPUT_FILE}"

WARP_EXCLUDE = {13335, 209242}

try:
    req = urllib.request.Request(url, headers={"User-Agent": "MikuInvidious-Anubis-Updater/1.0"})
    with urllib.request.urlopen(req, timeout=15) as resp:
        content = resp.read().decode("utf-8")
except Exception as e:
    sys.stderr.write(f"[!] Error fetching {url}: {e}\n")
    sys.exit(1)

asns = set()
for line in content.strip().splitlines():
    line = line.strip()
    if line.startswith("AS"):
        try:
            num = int(line[2:])
            if num not in WARP_EXCLUDE:
                asns.add(num)
        except ValueError:
            pass

sorted_asns = sorted(list(asns))

if not sorted_asns:
    sys.stderr.write("[!] Error: No ASNs found or downloaded file was empty.\n")
    sys.exit(1)

# Format into wrapped lines for clean YAML
chunk_size = 15
lines = []
for i in range(0, len(sorted_asns), chunk_size):
    chunk = sorted_asns[i:i + chunk_size]
    lines.append("      " + ", ".join(str(n) for n in chunk) + ",")

# Remove trailing comma on last line
if lines:
    lines[-1] = lines[-1].rstrip(",")

header = f"""# Auto-generated by update_vps_asns.sh
# Source: {url}
# Total ASNs: {len(sorted_asns)} (Cloudflare WARP 13335, 209242 explicitly excluded)

- name: weigh-vpsh-datacenter-asns
  action: WEIGH
  asns:
    match: [
"""
footer = """    ]
  weight:
    adjust: 15
"""

with open(tmp_file, "w") as f:
    f.write(header)
    f.write("\n".join(lines) + "\n")
    f.write(footer)

print(f"[+] Successfully extracted {len(sorted_asns)} ASNs to {tmp_file}")
EOF

# Atomically replace destination file
mv -f "${TMP_FILE}" "${OUTPUT_FILE}"
chmod 644 "${OUTPUT_FILE}"

echo "[+] Updated Anubis rule written to ${OUTPUT_FILE}"
